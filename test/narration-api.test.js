'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {tmpdir}=require('node:os');
const {makeRoom}=require('./helpers');
const game=require('../lib/game');
const dir=fs.mkdtempSync(path.join(tmpdir(),'werewolf-voice-'));
process.env.DATA_FILE=path.join(dir,'rooms.json');
const room=makeRoom();room.code='777771';room.host={sid:'a'.repeat(64),id:'host'};
room.players.forEach((p,i)=>p.sid=String(i+1).repeat(64));game.createGame(room);
fs.writeFileSync(process.env.DATA_FILE,JSON.stringify({rooms:{[room.code]:room}}));
const {server}=require('../server');
test('voice HTTP: host ownership, private action gates, pause persistence, and local WAV range delivery',async t=>{
 await new Promise(r=>server.listen(0,'127.0.0.1',r));const base=`http://127.0.0.1:${server.address().port}`;
 t.after(async()=>{server.closeAllConnections();await new Promise(r=>server.close(r));});
 const clientId='browser-owner-123456';
 async function req(actor,route,body){const sid=actor==='host'?room.host.sid:room.players[actor].sid;const r=await fetch(base+route,{method:body?'POST':'GET',headers:{cookie:`werewolf_sid=${sid}`,'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,body:await r.json()};}
 assert.equal((await req(0,'/api/narration',{action:'enable',clientId})).status,403);
 assert.equal((await req('host','/api/narration',{action:'enable',clientId})).status,200);
 assert.equal((await req('host','/api/narration',{action:'enable',clientId:'second-browser-12345'})).status,409);
 let state=(await req('host','/api/state')).body;assert.equal(state.room.narration.windowOpen,false);
 assert.equal(state.room.narration.plan.filter(c=>/\.(open|close)$/.test(c.cue)).length,8);
 assert.doesNotMatch(JSON.stringify(state.room.narration),/cardId|inspection|HIDDEN_WOLF|wolfTarget/);
 assert.equal((await req(0,'/api/action',{type:'TARGET',seat:2})).status,409);
 assert.equal((await req('host','/api/advance',{})).status,409);
 await req('host','/api/narration',{action:'pause',clientId});state=(await req('host','/api/state')).body;
 assert.equal(state.room.narration.paused,true);assert.equal(state.room.narration.windowOpen,false);
 assert.equal(JSON.parse(fs.readFileSync(process.env.DATA_FILE,'utf8')).rooms[room.code].narration.paused,true);
 await req('host','/api/narration',{action:'resume',clientId});assert.equal((await req(0,'/api/state')).body.room.narration.paused,false);
 await req('host','/api/narration',{action:'disable',clientId});assert.equal((await req('host','/api/advance',{})).status,409);
 assert.equal((await req('host','/api/narration',{action:'enable',clientId})).status,200);
 const manifest=await fetch(base+'/voicepacks/2023-6p-v02/pack.json');assert.equal(manifest.status,200);
 const wav=await fetch(base+'/voicepacks/2023-6p-v02/N00.wav',{headers:{Range:'bytes=0-11'}});
 assert.equal(wav.status,206);assert.match(wav.headers.get('content-type'),/audio\/wav/);
 assert.equal(Buffer.from(await wav.arrayBuffer()).toString('ascii',0,4),'RIFF');
 assert.equal((await fetch(base+'/voicepacks/2023-6p-v02/missing.wav')).status,404);
 assert.equal((await fetch(base+'/voicepacks/zh-neutral/pack.json')).status,404);
});
